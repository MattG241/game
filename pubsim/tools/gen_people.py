#!/usr/bin/env python3
"""Sculpts the pub's people as smooth meshes and writes them to assets/people/*.obj.

Each body part is a signed-distance model (rounded cones, ellipsoids, smooth unions and
subtractions) turned into triangles by marching cubes, then simplified to a phone-friendly
triangle budget. Parts are cut at the joints the game animates (shoulder, elbow, hip, knee,
neck), with overlapping rounded ends so joints never open up when limbs bend.

Coordinate conventions match scripts/npc/customer.gd: metres, +Y up, characters face -Z.
  torso_*   : in body space (hips at y 0.86, shoulders at y 1.42, neck top y 1.6)
  head_*    : head pivot space (pivot at y 1.68 in body space)
  upperarm_*: shoulder pivot space, hanging down -Y
  forearm_* : elbow pivot space, hand at the end (L/R mirrored so palms face inwards)
  thigh_*   : hip pivot space; shin_*: knee pivot space, shoe at the end
  hair_*, beard, cap: head pivot space
Painting (clothes, lips, brows, shoes) is done by shaders from these local coordinates.
Requires: numpy, scikit-image, pyfqmr.
"""
import os

import numpy as np
import pyfqmr
from skimage import measure

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "assets", "people")
os.makedirs(OUT, exist_ok=True)


# ------------------------------------------------------------------ SDF primitives (vectorised)
def length(v):
    return np.sqrt(np.sum(v * v, axis=-1))


def sphere(p, c, r):
    return length(p - np.asarray(c)) - r


def ellipsoid(p, c, r):
    r = np.asarray(r, np.float64)
    q = (p - np.asarray(c)) / r
    k0 = length(q)
    k1 = length(q / r)
    return k0 * (k0 - 1.0) / np.maximum(k1, 1e-9)


def round_cone(p, a, b, ra, rb):
    """Capsule from a to b whose radius goes from ra to rb."""
    a = np.asarray(a, np.float64)
    b = np.asarray(b, np.float64)
    ba = b - a
    pa = p - a
    h = np.clip(np.sum(pa * ba, axis=-1) / np.dot(ba, ba), 0.0, 1.0)
    r = ra + (rb - ra) * h
    return length(pa - ba * h[..., None]) - r


def rbox(p, c, half, r):
    q = np.abs(p - np.asarray(c)) - (np.asarray(half) - r)
    return length(np.maximum(q, 0.0)) + np.minimum(np.max(q, axis=-1), 0.0) - r


def smin(a, b, k):
    h = np.clip(0.5 + 0.5 * (b - a) / k, 0.0, 1.0)
    return b * (1 - h) + a * h - k * h * (1 - h)


def smax(a, b, k):
    return -smin(-a, -b, k)


def union(ds, k):
    d = ds[0]
    for e in ds[1:]:
        d = smin(d, e, k)
    return d


def noise3(p, freq, seed=0):
    """Cheap smooth value-ish noise from sines (good enough for hair and folds)."""
    x, y, z = p[..., 0] * freq, p[..., 1] * freq, p[..., 2] * freq
    return (np.sin(x * 1.7 + seed) * np.sin(y * 2.3 + seed * 0.7) * np.sin(z * 1.9 + seed * 1.3)
            + 0.5 * np.sin(x * 3.1 + y * 2.9 + seed) * np.sin(z * 3.7 - y * 1.3)) / 1.5


# ------------------------------------------------------------------ meshing
def mesh_sdf(sdf, lo, hi, voxel, target_tris, name, flip_x=False):
    lo = np.asarray(lo, np.float64)
    hi = np.asarray(hi, np.float64)
    n = np.ceil((hi - lo) / voxel).astype(int) + 1
    xs = [lo[i] + np.arange(n[i]) * voxel for i in range(3)]
    grid = np.stack(np.meshgrid(*xs, indexing="ij"), axis=-1)
    vol = sdf(grid.reshape(-1, 3)).reshape(n)
    verts, faces, _, _ = measure.marching_cubes(-vol, level=0.0, spacing=(voxel, voxel, voxel))
    verts += lo
    simp = pyfqmr.Simplify()
    simp.setMesh(verts, faces)
    simp.simplify_mesh(target_count=target_tris, aggressiveness=5, preserve_border=True, verbose=False)
    verts, faces, _ = simp.getMesh()
    verts = np.asarray(verts, np.float64)
    faces = np.asarray(faces, np.int64)
    # smooth normals from the field itself (exact, so shading is soft and seamless)
    e = 1e-4
    g = np.stack([sdf(verts + np.array([e, 0, 0])) - sdf(verts - np.array([e, 0, 0])),
                  sdf(verts + np.array([0, e, 0])) - sdf(verts - np.array([0, e, 0])),
                  sdf(verts + np.array([0, 0, e])) - sdf(verts - np.array([0, 0, e]))], axis=-1)
    normals = g / np.maximum(length(g)[..., None], 1e-9)
    # make every triangle counter-clockwise when seen from outside
    tri = verts[faces]
    fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    out = normals[faces].mean(axis=1)
    bad = np.sum(fn * out, axis=-1) < 0
    faces[bad] = faces[bad][:, [0, 2, 1]]
    if flip_x:
        verts = verts * np.array([-1.0, 1.0, 1.0])
        normals = normals * np.array([-1.0, 1.0, 1.0])
        faces = faces[:, [0, 2, 1]]
    path = os.path.join(OUT, name + ".obj")
    with open(path, "w") as f:
        f.write("# generated by tools/gen_people.py\n")
        for v in verts:
            f.write("v %.5f %.5f %.5f\n" % tuple(v))
        for nn in normals:
            f.write("vn %.4f %.4f %.4f\n" % tuple(nn))
        for t in faces + 1:
            f.write("f %d//%d %d//%d %d//%d\n" % (t[0], t[0], t[1], t[1], t[2], t[2]))
    print(f"{name}: {len(verts)} verts, {len(faces)} tris")


# ------------------------------------------------------------------ body parts
def torso(fem):
    def f(p):
        z_scaled = p * np.array([1.0, 1.0, 1.0 / 0.78])
        if fem:
            pelvis = ellipsoid(p, (0, 0.92, 0.0), (0.185, 0.12, 0.13))
            waist = round_cone(z_scaled, (0, 0.95, 0), (0, 1.2, 0), 0.15, 0.135) * 0.78
            chest = ellipsoid(p, (0, 1.3, 0.0), (0.165, 0.13, 0.115))
            bust = smin(sphere(p, (-0.065, 1.29, -0.085), 0.06), sphere(p, (0.065, 1.29, -0.085), 0.06), 0.03)
            sh = round_cone(p, (-0.18, 1.425, 0.01), (0.18, 1.425, 0.01), 0.055, 0.055)
            delt = smin(sphere(p, (-0.2, 1.405, 0.0), 0.05), sphere(p, (0.2, 1.405, 0.0), 0.05), 0.02)
            neck = round_cone(p, (0, 1.44, 0.01), (0, 1.62, 0.0), 0.05, 0.043)
            d = union([pelvis, waist, chest, bust, sh, delt, neck], 0.05)
        else:
            pelvis = ellipsoid(p, (0, 0.92, 0.0), (0.17, 0.11, 0.12))
            waist = round_cone(z_scaled, (0, 0.95, 0), (0, 1.22, 0), 0.158, 0.17) * 0.78
            chest = ellipsoid(p, (0, 1.3, -0.005), (0.2, 0.15, 0.13))
            sh = round_cone(p, (-0.22, 1.43, 0.01), (0.22, 1.43, 0.01), 0.066, 0.066)
            delt = smin(sphere(p, (-0.238, 1.405, 0.0), 0.058), sphere(p, (0.238, 1.405, 0.0), 0.058), 0.02)
            trap = smin(round_cone(p, (-0.18, 1.45, 0.02), (0, 1.53, 0.02), 0.05, 0.06),
                        round_cone(p, (0.18, 1.45, 0.02), (0, 1.53, 0.02), 0.05, 0.06), 0.03)
            neck = round_cone(p, (0, 1.45, 0.01), (0, 1.62, 0.0), 0.06, 0.052)
            d = union([pelvis, waist, chest, sh, delt, trap, neck], 0.05)
        # soft cloth folds at the waist and under the arms
        d += noise3(p, 40.0, 1.0) * 0.0025
        return d
    return f


def head(fem):
    def f(p):
        cran = ellipsoid(p, (0, 0.03, 0.012), (0.088, 0.1, 0.1))
        jaw_w = 0.068 if fem else 0.078
        face = ellipsoid(p, (0, -0.04, -0.028), (jaw_w, 0.072, 0.086))
        chin = sphere(p, (0, -0.098, -0.066), 0.026 if fem else 0.03)
        cheeks = smin(sphere(p, (-0.048, -0.008, -0.074), 0.028), sphere(p, (0.048, -0.008, -0.074), 0.028), 0.02)
        brow = round_cone(p, (-0.046, 0.034, -0.086), (0.046, 0.034, -0.086), 0.015 if fem else 0.018, 0.015 if fem else 0.018)
        nose = round_cone(p, (0, 0.02, -0.096), (0, -0.024, -0.116), 0.0085, 0.0135)
        wings = smin(sphere(p, (-0.013, -0.027, -0.104), 0.0095), sphere(p, (0.013, -0.027, -0.104), 0.0095), 0.01)
        lip_r = 0.0105 if fem else 0.009
        lips = smin(round_cone(p, (-0.021, -0.053, -0.102), (0.021, -0.053, -0.102), lip_r, lip_r),
                    round_cone(p, (-0.018, -0.067, -0.099), (0.018, -0.067, -0.099), lip_r * 1.05, lip_r * 1.05), 0.006)
        ears = smin(ellipsoid(p, (-0.084, 0.0, 0.012), (0.008, 0.026, 0.018)),
                    ellipsoid(p, (0.084, 0.0, 0.012), (0.008, 0.026, 0.018)), 0.01)
        neck = round_cone(p, (0, -0.06, 0.012), (0, -0.15, 0.02), 0.048 if fem else 0.055, 0.05 if fem else 0.058)
        d = union([cran, face, chin, cheeks, brow, nose, wings, ears, neck], 0.022)
        d = smin(d, lips, 0.008)
        # eye sockets and the mouth line
        sockets = smin(sphere(p, (-0.035, 0.012, -0.096), 0.019), sphere(p, (0.035, 0.012, -0.096), 0.019), 0.01)
        d = smax(d, -sockets, 0.012)
        mouth = round_cone(p, (-0.02, -0.06, -0.112), (0.02, -0.06, -0.112), 0.0025, 0.0025)
        d = smax(d, -mouth, 0.004)
        return d
    return f


def upper_arm(fem):
    k = 0.85 if fem else 1.0
    def f(p):
        d = round_cone(p, (0, 0.01, 0), (0, -0.29, 0), 0.056 * k, 0.042 * k)
        d = smin(d, sphere(p, (0, -0.005, 0), 0.054 * k), 0.02)
        d = smin(d, ellipsoid(p, (0, -0.13, 0.012), (0.05 * k, 0.09, 0.05 * k)), 0.02)
        return d + noise3(p, 50.0, 3.0) * 0.0015
    return f


def forearm(fem):
    k = 0.85 if fem else 1.0
    def f(p):
        arm = round_cone(p, (0, 0.0, 0), (0, -0.25, 0), 0.044 * k, 0.03 * k)
        arm = smin(arm, ellipsoid(p, (0, -0.07, 0.0), (0.045 * k, 0.08, 0.042 * k)), 0.02)
        wrist = round_cone(p, (0, -0.25, 0), (0, -0.28, -0.003), 0.029 * k, 0.026 * k)
        # hand: palm faces +x (inwards for the left arm; mirrored for the right)
        palm = rbox(p, (0.004, -0.315, -0.004), (0.013 * k, 0.04, 0.036 * k), 0.012)
        fingers = []
        for i in range(4):
            z = (-0.024 + i * 0.016) * k
            ln = [0.045, 0.05, 0.047, 0.04][i] * (0.92 if fem else 1.0)
            a = (0.0, -0.345, z)
            b = (0.012, -0.345 - ln, z - 0.004)
            fingers.append(round_cone(p, a, b, 0.0085 * k, 0.0072 * k))
        thumb = round_cone(p, (0.008, -0.295, -0.035 * k), (0.022, -0.335, -0.052 * k), 0.011 * k, 0.009 * k)
        hand = union([palm] + fingers + [thumb], 0.008)
        d = union([arm, wrist], 0.015)
        d = smin(d, hand, 0.012)
        d = smin(d, sphere(p, (0, 0.0, 0), 0.045 * k), 0.015)
        return d
    return f


def thigh(fem):
    def f(p):
        d = round_cone(p, (0, 0.02, 0), (0, -0.42, 0), 0.085 if fem else 0.08, 0.055)
        d = smin(d, sphere(p, (0, -0.0, 0.025), 0.08 if fem else 0.075), 0.03)
        d = smin(d, sphere(p, (0, -0.42, 0), 0.055), 0.02)
        return d + noise3(p, 45.0, 5.0) * 0.002
    return f


def shin(fem):
    def f(p):
        leg = round_cone(p, (0, 0.0, 0), (0, -0.37, 0), 0.054, 0.034)
        leg = smin(leg, ellipsoid(p, (0, -0.12, 0.02), (0.05, 0.11, 0.05)), 0.03)
        leg = smin(leg, sphere(p, (0, 0.0, 0), 0.055), 0.02)
        shoe = smin(ellipsoid(p, (0, -0.41, -0.035), (0.045, 0.038, 0.115)),
                    ellipsoid(p, (0, -0.4, 0.035), (0.04, 0.045, 0.05)), 0.03)
        shoe = smax(shoe, -(p[..., 1] + 0.445), 0.005)  # flat sole
        return smin(leg, shoe, 0.02)
    return f


# ------------------------------------------------------------------ hair and hats (head space)
def cranium_shell(p, grow):
    grow = np.broadcast_to(np.asarray(grow, np.float64), p.shape[:-1])
    r = np.stack([0.086 + grow, 0.106 + grow, 0.102 + grow], axis=-1)
    return ellipsoid(p, (0, 0.04, 0.014), r)


def face_cut(p):
    """Keeps hair off the face: a rounded region in front of the forehead line."""
    return rbox(p, (0, -0.05, -0.12), (0.075, 0.09, 0.07), 0.03)


def hair_short(p):
    d = cranium_shell(p, 0.012 + noise3(p, 90.0, 2.0) * 0.003)
    d = smax(d, -(p[..., 1] + 0.0), 0.02)                    # nothing below ear level
    d = smax(d, -face_cut(p) + 0.0, 0.015)
    return d


def hair_long(p):
    d = cranium_shell(p, 0.014 + noise3(p, 80.0, 4.0) * 0.003)
    d = smax(d, -face_cut(p), 0.015)
    back = rbox(p, (0, -0.12, 0.05), (0.085, 0.14, 0.055), 0.04) + noise3(p, 60.0, 7.0) * 0.004
    sides = smin(rbox(p, (-0.085, -0.08, 0.0), (0.02, 0.11, 0.05), 0.018),
                 rbox(p, (0.085, -0.08, 0.0), (0.02, 0.11, 0.05), 0.018), 0.02)
    return union([d, back, sides], 0.03)


def hair_bob(p):
    d = cranium_shell(p, 0.018 + noise3(p, 70.0, 6.0) * 0.003)
    d = smax(d, -(p[..., 1] + 0.075), 0.015)
    d = smax(d, -face_cut(p), 0.015)
    return d


def hair_bun(p):
    d = hair_short(p)
    return smin(d, sphere(p, (0, 0.1, 0.095), 0.048), 0.02)


def hair_ponytail(p):
    d = hair_short(p)
    tail = round_cone(p, (0, 0.06, 0.1), (0, -0.16, 0.14), 0.035, 0.018) + noise3(p, 80.0, 9.0) * 0.003
    return smin(d, tail, 0.02)


def hair_curly(p):
    d = cranium_shell(p, 0.02 + (noise3(p, 110.0, 1.0) * 0.5 + 0.5) * 0.008)
    d = smax(d, -(p[..., 1] + 0.01), 0.02)
    d = smax(d, -face_cut(p), 0.015)
    return d


def beard(p):
    jaw = ellipsoid(p, (0, -0.06, -0.03), (0.085, 0.085, 0.095)) + noise3(p, 110.0, 3.0) * 0.003
    d = smax(jaw, (p[..., 1] - (-0.035)), 0.01)              # below the cheekbones only
    mouth_hole = ellipsoid(p, (0, -0.06, -0.12), (0.03, 0.016, 0.04))
    d = smax(d, -mouth_hole, 0.006)
    d = smax(d, (p[..., 2] - 0.03), 0.02)                    # not behind the ears
    return d


def flat_cap(p):
    crown = ellipsoid(p, (0, 0.105, -0.005), (0.1, 0.045, 0.112))
    crown = smax(crown, -(p[..., 1] - 0.075), 0.01)
    peak = ellipsoid(p, (0, 0.085, -0.1), (0.085, 0.012, 0.05))
    return smin(crown, peak, 0.015)


def grip_hand(p):
    """The bartender's right hand round a pint (glass axis = +Y through the origin, radius 0.047):
    back of the hand on the right, fingers curled round the far side, thumb across the near side,
    wrist and forearm running down and back towards the viewer (+X, -Y, +Z)."""
    r = 0.049
    parts = []
    back = ellipsoid(p, (r + 0.012, 0.074, 0.006), (0.02, 0.046, 0.044))
    parts.append(back)
    for i in range(4):
        y = 0.048 + i * 0.018
        prev = None
        for k in range(4):
            a0 = np.radians(-10.0 - k * 26.0)
            a1 = np.radians(-10.0 - (k + 1) * 26.0)
            pa = (np.cos(a0) * r, y, np.sin(a0) * r)
            pb = (np.cos(a1) * r, y - 0.002 * k, np.sin(a1) * r)
            rr = 0.0088 - k * 0.0007
            parts.append(round_cone(p, pa, pb, rr, rr - 0.0006))
    thumb_a = (r + 0.004, 0.078, 0.024)
    thumb_b = (0.03, 0.088, 0.04)
    thumb_c = (0.008, 0.093, 0.046)
    parts.append(round_cone(p, thumb_a, thumb_b, 0.0115, 0.0098))
    parts.append(round_cone(p, thumb_b, thumb_c, 0.0098, 0.0085))
    d = union(parts, 0.007)
    wrist_dir = np.array([0.55, -0.62, 0.56])
    wrist_dir = wrist_dir / np.linalg.norm(wrist_dir)
    w0 = np.array([r + 0.012, 0.04, 0.012])
    arm = round_cone(p, tuple(w0), tuple(w0 + wrist_dir * 0.32), 0.026, 0.036)
    return smin(d, arm, 0.015)


def skirt(p):
    d = round_cone(p, (0, 0.92, 0), (0, 0.5, 0), 0.19, 0.26)
    d = smax(d, -(p[..., 1] - 0.5), 0.01)
    return d + noise3(p * np.array([1.0, 0.2, 1.0]), 40.0, 2.0) * 0.006


def main():
    for fem, tag in [(False, "m"), (True, "f")]:
        mesh_sdf(torso(fem), (-0.3, 0.76, -0.2), (0.3, 1.66, 0.2), 0.006, 2200, "torso_" + tag)
        mesh_sdf(head(fem), (-0.11, -0.17, -0.14), (0.11, 0.16, 0.13), 0.0035, 2200, "head_" + tag)
        mesh_sdf(upper_arm(fem), (-0.08, -0.34, -0.08), (0.08, 0.08, 0.08), 0.005, 300, "upperarm_" + tag)
        mesh_sdf(forearm(fem), (-0.06, -0.42, -0.08), (0.06, 0.06, 0.06), 0.003, 900, "forearm_l_" + tag)
        mesh_sdf(forearm(fem), (-0.06, -0.42, -0.08), (0.06, 0.06, 0.06), 0.003, 900, "forearm_r_" + tag, flip_x=True)
        mesh_sdf(thigh(fem), (-0.1, -0.5, -0.1), (0.1, 0.12, 0.12), 0.006, 350, "thigh_" + tag)
        mesh_sdf(shin(fem), (-0.08, -0.47, -0.17), (0.08, 0.07, 0.1), 0.004, 600, "shin_" + tag)
    hb = ((-0.13, -0.3, -0.15), (0.13, 0.2, 0.2))
    for name, fn in [("hair_short", hair_short), ("hair_long", hair_long), ("hair_bob", hair_bob),
                     ("hair_bun", hair_bun), ("hair_ponytail", hair_ponytail), ("hair_curly", hair_curly),
                     ("beard", beard), ("cap", flat_cap)]:
        mesh_sdf(fn, hb[0], hb[1], 0.0045, 900, name)
    mesh_sdf(skirt, (-0.3, 0.45, -0.3), (0.3, 0.98, 0.3), 0.008, 500, "skirt")
    mesh_sdf(grip_hand, (-0.03, -0.25, -0.07), (0.27, 0.15, 0.27), 0.0025, 2400, "hand_grip")


if __name__ == "__main__":
    main()
